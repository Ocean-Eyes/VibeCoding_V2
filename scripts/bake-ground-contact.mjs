// Offline mesh-constrained paths. Select the whole continuous sequence rather
// than fixing each frame independently, which can flip an elbow across a limb.
import{sampleGroundAuthored}from'../src/ground-motion.js';
import{GROUND_CONTACT_RATE}from'../src/ground-contact-data.js';
import{groundContactShapes}from'../src/throw-render.js';
import{bodyShapes,bodyOverlap,ellipsoidBody}from'../src/throw-body.js';
import{limb,add,sub,mul,unit,cross,dot}from'../src/throw-motion.js';
import fs from'node:fs';
const turn=(v,k,a)=>add(add(mul(v,Math.cos(a)),mul(cross(k,v),Math.sin(a))),mul(k,dot(k,v)*(1-Math.cos(a))));
const rate=GROUND_CONTACT_RATE;
function solve(side,rightFrames=[]){
 const layers=[];
 for(let f=0;f<=3*rate;f++){
  const t=f/rate,p=sampleGroundAuthored('ude-garami',t,rightFrames),arm=p.tori.arms[side],axis=unit(sub(arm.end,arm.root)),goal=arm.joint;
  if(arm.reachError>1e-8)throw Error('Reach '+side+' '+t);
  const orig=sub(limb(arm.root,arm.end,.33,.31,[-1,0,0]).joint,arm.root);
  const fixed=groundContactShapes(p).filter(s=>side==='right'?s.id.startsWith('uke.'):!s.id.startsWith('tori.left'));
  const obstacles=[...fixed,...bodyShapes(p.uke).filter(s=>!/^arm\.|^hand\./.test(s.id))];
  if(side==='right')obstacles.push(ellipsoidBody('left.shoulder',p.tori.arms.left.root,[.055,.055,.055],[[1,0,0],[0,1,0],[0,0,1]]));
  const layer=[];
  for(let angle=0;angle<360;angle+=3){
   arm.joint=add(arm.root,turn(orig,axis,angle*Math.PI/180));if(arm.joint[1]<.06)continue;
   const shapes=groundContactShapes(p,'tori.'+side);let hit=false;
   for(const a of shapes){for(const b of obstacles){if(bodyOverlap(a,b,a.id.includes('.hand.')?0:-.003)){hit=true;break;}}if(hit)break;}
   if(hit)continue;
   const joint=[...arm.joint],goalCost=dot(sub(joint,goal),sub(joint,goal))*.001;
   let cost=f===0?goalCost:Infinity,from=-1;
   if(f>0)for(const [i,previous]of layers[f-1].entries()){
    const delta=sub(joint,previous.joint),distance=dot(delta,delta);if(distance>.045**2)continue;
    const candidate=previous.cost+distance+goalCost;
    if(candidate<cost){cost=candidate;from=i;}
   }
   if(Number.isFinite(cost))layer.push({joint,cost,from});
  }
  if(!layer.length)throw Error('No continuous '+side+' path at '+t);
  layers.push(layer);if(f%20===0)console.log(side,t,layer.length);
 }
 let index=layers.at(-1).reduce((best,n,i,a)=>n.cost<a[best].cost?i:best,0),frames=[];
 for(let f=layers.length-1;f>=0;f--){const n=layers[f][index];frames.unshift(n.joint);index=n.from;}
 return frames;
}
const right=solve('right'),left=solve('left',right);
const data=frames=>frames.map(v=>JSON.stringify(v.map(n=>+n.toFixed(8)))).join(',\n');
fs.writeFileSync(new URL('../src/ground-contact-data.js',import.meta.url),'// Generated by scripts/bake-ground-contact.mjs. Visible-mesh contact paths, metres.\nexport const GROUND_CONTACT_RATE='+rate+';\nexport const UDE_RIGHT_ELBOWS=[\n'+data(right)+'\n];\nexport const UDE_LEFT_ELBOWS=[\n'+data(left)+'\n];\n');
