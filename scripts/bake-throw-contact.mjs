import {solve} from './solve-throw-contact.mjs';
import {sampleThrowAuthored,THROW_KEYS} from '../src/throw-motion.js';
import {CONTACT_TRACKS} from '../src/throw-contact-data.js';
import {bodyIntersections} from '../src/throw-body.js';
import {writeFile} from 'node:fs/promises';
const rate=40,requested=process.argv[2],tracks=requested?structuredClone(CONTACT_TRACKS):{};
if(requested&&!THROW_KEYS[requested])throw Error('Unknown throw: '+requested);
for(const id of requested?[requested]:Object.keys(THROW_KEYS)){
 const frames=[];let previous;const hits=[];
 for(let i=0;i<=3*rate;i++){
  const raw=sampleThrowAuthored(id,i/rate),solved=solve(raw,previous);previous={raw,solved};
  const numbers=[];for(const who of ['tori','uke']){numbers.push(...solved[who].pelvis);for(const kind of ['arms','legs'])for(const side of ['left','right']){const l=solved[who][kind][side];numbers.push(...l.joint,...l.end);}}
  frames.push(numbers.map(v=>Math.round(v*1e6)/1e6));
  for(const hit of bodyIntersections(solved))hits.push({time:i/rate,...hit});
 }
 tracks[id]=frames;console.log(id,JSON.stringify({frames:frames.length,intersections:hits.length,worst:hits.sort((a,b)=>b.depth-a.depth)[0]}));
 if(hits.length)throw Error('Unresolved displayed-body intersections: '+id);
}
const data=Object.entries(tracks).map(([id,frames])=>JSON.stringify(id)+':[\n'+frames.map(frame=>JSON.stringify(frame)).join(',\n')+'\n]').join(',\n');
await writeFile(new URL('../src/throw-contact-data.js',import.meta.url),`// Generated by scripts/bake-throw-contact.mjs. Metres; never solved during playback.\nexport const CONTACT_RATE=${rate};\nexport const CONTACT_TRACKS={\n${data}\n};\n`);
